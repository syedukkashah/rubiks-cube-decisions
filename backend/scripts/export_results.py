"""Export saved benchmark evidence without network or inference calls."""

import argparse
import csv
import json
import sys
from collections import defaultdict
from decimal import Decimal
from pathlib import Path
from statistics import mean

if __package__ in {None, ""}:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.config import BACKEND_DIR, CHAT_MODEL, Settings
from app.schemas import RunSnapshot
from app.stats import compute_stats
from app.storage import RunStore


def export_results(runs_dir, ledger_path, output_dir):
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    ledger_path = Path(ledger_path)
    ledger = (
        [json.loads(line) for line in ledger_path.read_text(encoding="utf-8").splitlines()]
        if ledger_path.exists()
        else []
    )
    by_run, by_model = defaultdict(Decimal), defaultdict(Decimal)
    for row in ledger:
        cost = Decimal(str(row["cost_usd"]))
        by_run[row["run_id"]] += cost
        by_model[row["model_id"]] += cost
    lines = [
        "# Benchmark results",
        "",
        "Opus configuration: adaptive thinking at low effort "
        "(or the documented omit compatibility variant), immediate-answer instruction, "
        "and a hard total-output cap. This cap may limit solution quality.",
        "",
        f"Total usage spend: ${sum(by_run.values(), Decimal(0)):.6f}",
        "",
        "## Spend by model",
        "",
        "| Model | USD |",
        "|---|---:|",
    ]
    lines.extend(f"| {model} | {cost:.6f} |" for model, cost in sorted(by_model.items()))
    lines.extend(
        ["", "## Spend by run (includes smoke/calibration)", "", "| Run | USD |", "|---|---:|"]
    )
    lines.extend(f"| {run} | {cost:.6f} |" for run, cost in sorted(by_run.items()))
    for stored in RunStore(Path(runs_dir)).load("runs"):
        snapshot = RunSnapshot.model_validate(stored["snapshot"])
        # IDs generated by this backend are safe; reject path traversal in imported evidence.
        if Path(snapshot.run_id).name != snapshot.run_id or any(
            char in snapshot.run_id for char in ("/", "\\", ":")
        ):
            raise ValueError("Unsafe persisted run ID")
        stats = compute_stats(snapshot)
        metrics = [m for m in stored.get("call_metrics", []) if m["model_id"] == CHAT_MODEL]
        accepted = [m for m in metrics if m["accepted"]]

        def avg(field):
            values = [m["usage"][field] for m in accepted if m["usage"].get(field) is not None]
            return mean(values) if values else None

        extra = {
            "opus_avg_completion_tokens_per_move": avg("output_tokens"),
            "opus_avg_reasoning_tokens_per_move": avg("reasoning_tokens"),
            "opus_truncation_count": sum(m["finish_reason"] == "length" for m in metrics),
            "opus_max_tokens": stored.get("execution_config", {}).get("chat_max_tokens"),
            "opus_reasoning_effort": stored.get("execution_config", {}).get(
                "chat_reasoning_effort"
            ),
        }
        rows = []
        for model in stats.models:
            cost = sum(
                (
                    Decimal(str(row["cost_usd"]))
                    for row in ledger
                    if row["run_id"] == snapshot.run_id and row["model_id"] == model.model_id
                ),
                Decimal(0),
            )
            rows.append(
                {
                    **model.model_dump(),
                    "spend_usd": str(cost),
                    **{
                        key: value if model.model_id == CHAT_MODEL else None
                        for key, value in extra.items()
                    },
                }
            )
        with (output_dir / f"{snapshot.run_id}.csv").open("w", newline="", encoding="utf-8") as out:
            writer = csv.DictWriter(out, fieldnames=list(rows[0]) if rows else [])
            writer.writeheader()
            writer.writerows(rows)
        lines.extend(
            [
                "",
                f"## {snapshot.run_id}",
                "",
                f"Mode: {'live' if stored['live'] else 'mock'}; status: {snapshot.status}. "
                f"Spend: ${by_run[snapshot.run_id]:.6f}.",
                f"Opus max_tokens: {extra['opus_max_tokens']}; "
                f"reasoning setting: {extra['opus_reasoning_effort']} "
                "(omit means provider-default adaptive thinking).",
                "",
                "Opus accepted-move mean completion tokens: "
                f"{extra['opus_avg_completion_tokens_per_move']}; "
                f"reasoning tokens: {extra['opus_avg_reasoning_tokens_per_move']}; "
                f"truncated attempts: {extra['opus_truncation_count']}.",
                "",
                "| Model | Trials | Solved | Success % | Avg latency ms | Avg time s | "
                "Moves | Avg moves | Gap | Invalid | Retries | Timeouts |",
                "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
            ]
        )
        fields = (
            "model_id",
            "trials",
            "solved_trials",
            "success_rate_pct",
            "avg_move_latency_ms",
            "avg_total_time_s",
            "total_moves",
            "avg_moves_per_trial",
            "avg_optimality_gap",
            "invalid_move_count",
            "retry_count",
            "timeout_count",
        )
        lines.extend("| " + " | ".join(str(row[f]) for f in fields) + " |" for row in rows)
    (output_dir / "benchmark_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=BACKEND_DIR / "results")
    args = parser.parse_args()
    settings = Settings.from_env()
    export_results(settings.runs_dir, settings.spend_ledger_path, args.output_dir)


if __name__ == "__main__":
    main()
